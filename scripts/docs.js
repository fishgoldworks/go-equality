'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

function publicCallForms(api) {
    const functions = Object.entries(api).filter(([, value]) => typeof value === 'function');
    return functions.map(([name]) => name).concat(functions.flatMap(([name, fn]) =>
        Object.entries(Object.getOwnPropertyDescriptors(fn))
            .filter(([, descriptor]) => typeof descriptor.value === 'function')
            .map(([method]) => name + '.' + method)));
}

function renderReadme(template, metadata, api) {
    const names = publicCallForms(api);
    const minimumNode = /^>=(\d+\.\d+\.\d+)$/.exec(metadata.engines.node);
    assert.ok(minimumNode, 'The README template expects a single minimum Node version.');
    const fields = {
        VERSION:metadata.version,
        LICENSE:metadata.license,
        NODE_MIN_VERSION:minimumNode[1],
        TYPESCRIPT_VERSION:metadata.devDependencies.typescript,
        API_COUNT:String(names.length),
        TOC:'{{TOC}}'
    };
    const source = template.replace(/\r\n/g, '\n').replace(/\{\{([A-Z_]+)\}\}/g, (_, field) => {
        assert.ok(Object.hasOwn(fields, field), 'Unknown template field: ' + field);
        assert.equal(typeof fields[field], 'string', 'Missing metadata for ' + field);
        return fields[field];
    });
    assert.equal(source.split('{{TOC}}').length, 2, 'The template must contain exactly one table-of-contents field.');

    const contents = [];
    const documented = [];
    const anchors = new Map();
    let fence;
    let includeContents = false;
    let includeApi = false;
    let minimumLevel = 6;
    for (const line of source.split('\n')) {
        const marker = /^ {0,3}(`{3,}|~{3,})(.*)$/.exec(line);
        if (fence) {
            if (marker && marker[1][0] === fence[0] && marker[1].length >= fence.length && !marker[2].trim()) fence = undefined;
            continue;
        }
        if (marker) { fence = marker[1]; continue; }
        if (line === '{{TOC}}') { includeContents = true; continue; }
        const heading = /^(#{1,6}) (.+)$/.exec(line);
        if (!heading) continue;
        const level = heading[1].length;
        const title = heading[2];
        const anchor = title.toLowerCase().replace(/[`*]/g, '').replace(/[^\p{L}\p{N}\s_-]/gu, '').replace(/ /g, '-');
        const count = anchors.get(anchor) || 0;
        anchors.set(anchor, count + 1);
        if (level === 3 && title === 'Equality') includeApi = true;
        else if (level <= 3) includeApi = false;
        if (includeApi && level === 4) documented.push(title);
        if (level === 2 && title === 'License') includeContents = false;
        if (includeContents) {
            minimumLevel = Math.min(minimumLevel, level);
            contents.push('    '.repeat(level - minimumLevel) + '*   [' + title + '](#' + anchor + (count ? '-' + count : '') + ')');
        }
    }
    assert.deepEqual([...documented].sort(), [...names].sort(), 'Documentation must cover all public call forms exactly once.');
    return source.replace('{{TOC}}', () => contents.join('\n'))
        .replace(/^(# .+\n)/, '$1\n<!-- Generated by npm run docs; edit scripts/README.template.md. -->\n');
}

module.exports = renderReadme;
if (require.main === module) {
    const args = process.argv.slice(2);
    assert.ok(args.length === 0 || (args.length === 1 && args[0] === '--check'), 'Usage: node scripts/docs.js [--check]');
    const root = path.resolve(__dirname, '..');
    const template = fs.readFileSync(path.join(__dirname, 'README.template.md'), 'utf8');
    const readme = renderReadme(template, require('../package.json'), require('../index.js'));
    if (args[0] === '--check') {
        const file = path.join(root, 'README.md');
        assert.ok(fs.existsSync(file) && fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') === readme,
            'Stale README.md. Run npm run docs.');
        console.log('Generated documentation is current.');
    } else {
        fs.writeFileSync(path.join(root, 'README.md'), readme);
        console.log('Generated README metadata, API coverage and table of contents.');
    }
}
