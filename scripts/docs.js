'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

function publicCallForms(api) {
  const functions = Object.entries(api).filter(([, value]) => typeof value === 'function');
  return functions
    .map(([name]) => name)
    .concat(
      functions.flatMap(([name, fn]) =>
        Object.entries(Object.getOwnPropertyDescriptors(fn))
          .filter(([, descriptor]) => typeof descriptor.value === 'function')
          .map(([method]) => name + '.' + method)
      )
    );
}

function renderDocument(template, metadata, api, templateName) {
  const names = publicCallForms(api);
  const minimumNode = /^>=(\d+\.\d+\.\d+)$/.exec(metadata.engines.node);
  assert.ok(minimumNode, 'The README template expects a single minimum Node version.');
  const fields = {
    VERSION: metadata.version,
    LICENSE: metadata.license,
    NODE_MIN_VERSION: minimumNode[1],
    TYPESCRIPT_VERSION: metadata.devDependencies.typescript,
    TOC: '{{TOC}}'
  };
  const source = template.replace(/\r\n/g, '\n').replace(/\{\{([A-Z_]+)\}\}/g, (_, field) => {
    assert.ok(Object.hasOwn(fields, field), 'Unknown template field: ' + field);
    assert.equal(typeof fields[field], 'string', 'Missing metadata for ' + field);
    return fields[field];
  });
  assert.equal(source.split('{{TOC}}').length, 2, 'The template must contain exactly one table-of-contents field.');

  const contents = [];
  const documented = [];
  const anchors = new Map();
  let fence;
  let includeContents = false;
  let includeApi = false;
  for (const line of source.split('\n')) {
    const marker = /^ {0,3}(`{3,}|~{3,})(.*)$/.exec(line);
    if (fence) {
      if (marker && marker[1][0] === fence[0] && marker[1].length >= fence.length && !marker[2].trim()) {
        fence = undefined;
      }
      continue;
    }
    if (marker) {
      fence = marker[1];
      continue;
    }
    if (line === '{{TOC}}') {
      includeContents = true;
      continue;
    }
    const heading = /^(#{1,6}) (.+)$/.exec(line);
    if (!heading) {
      continue;
    }
    const level = heading[1].length;
    const title = heading[2];
    const anchor = title
      .toLowerCase()
      .replace(/[`*]/g, '')
      .replace(/[^\p{L}\p{N}\s_-]/gu, '')
      .replace(/ /g, '-');
    const count = anchors.get(anchor) || 0;
    anchors.set(anchor, count + 1);
    if (level === 2 && title === 'Equality') {
      includeApi = true;
    } else if (level <= 2) {
      includeApi = false;
    }
    if (includeApi && level === 3) {
      const signature = /^`([\w.$]+)\(.*\)`$/.exec(title);
      assert.ok(signature, 'Public API headings must include a signature: ' + title);
      documented.push(signature[1]);
    }
    const selectedSubsection = level === 3 && ['Supported types', 'Custom equality'].includes(title);
    if (includeContents && (level === 2 || (templateName === 'API' && selectedSubsection))) {
      contents.push('  '.repeat(level - 2) + '- [' + title + '](#' + anchor + (count ? '-' + count : '') + ')');
    }
  }
  if (templateName === 'API') {
    assert.deepEqual(
      [...documented].sort(),
      [...names].sort(),
      'Documentation must cover all public call forms exactly once.'
    );
  }
  return source
    .replace('{{TOC}}', () => contents.join('\n'))
    .replace(
      /^(# .+\n)/,
      (_, title) => title + '\n<!-- Generated by npm run docs; edit scripts/' + templateName + '.template.md. -->\n'
    );
}

function renderDocuments(templates, metadata, api) {
  const reference = renderDocument(templates.API, metadata, api, 'API');
  const section = reference.split('## API summary\n')[1]?.split('\n## ')[0];
  const summary = section?.match(/^\|[^\n]+\n(?:\|[^\n]+\n)+/m)?.[0].trimEnd();
  assert.ok(summary, 'The API reference must contain an API summary table.');
  const documented = [...summary.matchAll(/\[`([\w.$]+)\([^`]*`\]\(#[^)]+\)/g)].map((match) => match[1]);
  assert.deepEqual(
    documented.sort(),
    publicCallForms(api).sort(),
    'The API summary must cover all public call forms exactly once.'
  );
  assert.equal(
    templates.README.split('{{API_SUMMARY}}').length,
    2,
    'The README must contain exactly one API summary field.'
  );
  const overview = templates.README.replace('{{API_SUMMARY}}', () => summary.replace(/\]\(#/g, '](docs/API.md#'));
  return {
    'README.md': renderDocument(overview, metadata, api, 'README'),
    'docs/API.md': reference
  };
}

module.exports = renderDocuments;
if (require.main === module) {
  const args = process.argv.slice(2);
  assert.ok(args.length === 0 || (args.length === 1 && args[0] === '--check'), 'Usage: node scripts/docs.js [--check]');
  const root = path.resolve(__dirname, '..');
  const templates = Object.fromEntries(
    ['README', 'API'].map((name) => [name, fs.readFileSync(path.join(__dirname, name + '.template.md'), 'utf8')])
  );
  const documents = renderDocuments(templates, require('../package.json'), require('../index.js'));
  for (const [name, text] of Object.entries(documents)) {
    const file = path.join(root, name);
    if (args[0] === '--check') {
      assert.ok(
        fs.existsSync(file) && fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') === text,
        'Stale ' + name + '. Run npm run docs.'
      );
    } else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, text);
    }
  }
  console.log(
    args[0] === '--check'
      ? 'Generated documentation is current.'
      : 'Generated README.md and docs/API.md with shared API summary, metadata and navigation.'
  );
}
